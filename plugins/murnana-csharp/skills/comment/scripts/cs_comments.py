#!/usr/bin/env python3
"""List, lint and guard comments in C# files.

Usage:
  cs_comments.py list FILE...           Print every comment as `file:line: KIND: text`, then
                                        every public/protected declaration in a public type
                                        without an XML doc comment as
                                        `file:line: UNDOCUMENTED: <declaration>`.
                                        Add --internal to also flag internal ones.
  cs_comments.py lint FILE...           Check each `///` block: well-formed XML, <summary> (or
                                        <inheritdoc/>), <param>/<typeparam> names against the
                                        signature, <returns> on void. Prints
                                        `file:line: ERROR|WARN CODE: message`, or `OK file`.
                                        Exit 1 if any ERROR.
  cs_comments.py snapshot FILE...       Copy FILEs to a new temporary directory and print its
                                        path. Run before editing.
  cs_comments.py check --base DIR FILE...
                                        Exit 1 if any file's code (everything except comments
                                        and whitespace) differs from its copy in DIR, or if a
                                        DIRECTIVE or LICENSE comment was changed or removed.
  cs_comments.py check --rev REV FILE...
                                        Same, comparing against a git revision instead.

Comment KIND is one of: DOC (/// or /** */), LICENSE (a copyright or license comment
before the first line of code), DIRECTIVE (ReSharper disable/restore, <auto-generated>,
NOSONAR, StyleCop, csharpier-ignore, dotnet_diagnostic), TODO, FIXME, LINE (//), BLOCK (/* */).
The lexer understands regular, verbatim (@""), interpolated ($"" with {}) and raw
(\"\"\"...\"\"\") strings and char literals, so `"//"` in a string is not a comment.
Interface members without an access modifier and `override` members are not listed:
the compiler's CS1591 covers the first, <inheritdoc/> the second.

Lint codes: XML_MALFORMED, SUMMARY_MISSING, PARAM_UNKNOWN, PARAM_MISSING,
TYPEPARAM_UNKNOWN, RETURNS_ON_VOID, ORPHAN_DOC.
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET

DIRECTIVE = re.compile(
    r"^(?://|/\*)\s*(?:ReSharper\s+(?:disable|restore)|<auto-generated|NOSONAR|StyleCop|csharpier-ignore"
    r"|dotnet_diagnostic|noinspection)", re.IGNORECASE)
MODS = (r"public|protected|internal|private|static|readonly|virtual|override|abstract|sealed|async|unsafe"
        r"|extern|new|partial|const|volatile|required|file|fixed")
DECL = re.compile(r"^[ \t]*(?:\[[^\]\n]*\][ \t]*)*(?P<mods>(?:(?:" + MODS + r")[ \t]+)+)(?P<rest>[^\n]*)", re.M)
TYPE_DECL = re.compile(r"(?:record\s+(?:class|struct)|class|struct|interface|record|enum)\s+(\w+)")
NAMESPACE = re.compile(r"^[ \t]*namespace\s+[\w.]+", re.M)


# ---------------------------------------------------------------- lexer

def lex(src):
    """Return (code_tokens, comments, masked).

    comments: list of (start, end, line, text, before_code).
    masked: src with every comment and string body replaced by spaces (newlines kept).
    """
    n = len(src)
    masked = list(src)
    code = []
    comments = []
    seen_code = False

    def blank(a, b):
        for k in range(a, b):
            if masked[k] != "\n":
                masked[k] = " "

    def skip_string(i):
        """i at the start of a string literal (prefixes included); return its end."""
        m = re.compile(r'(\$*)(@?)(\$*)("+)').match(src, i)
        dollars = len(m.group(1)) + len(m.group(3))
        verbatim = bool(m.group(2))
        quotes = len(m.group(4))
        j = m.end()
        if quotes >= 3:  # raw string literal: ends at the same number of quotes
            end = src.find('"' * quotes, j)
            return n if end == -1 else end + quotes
        if quotes == 2 and not verbatim:  # empty string ""
            return j
        if quotes == 2:  # @"" then content starting with an escaped quote
            j -= 1
        while j < n:
            ch = src[j]
            if verbatim and src.startswith('""', j):
                j += 2
            elif ch == '"':
                return j + 1
            elif ch == "\\" and not verbatim:
                j += 2
            elif ch == "\n" and not verbatim:
                return j
            elif dollars and src.startswith("{{", j):
                j += 2
            elif dollars and ch == "{":
                depth = 1
                j += 1
                while j < n and depth:
                    if src[j] == '"' or (src[j] in "$@" and re.match(r'[$@]+"', src[j:j + 4])):
                        j = skip_string(j)
                        continue
                    depth += {"{": 1, "}": -1}.get(src[j], 0)
                    j += 1
            else:
                j += 1
        return n

    i, line = 0, 1
    while i < n:
        c = src[i]
        j = None
        if src.startswith("//", i):
            j = src.find("\n", i)
            j = n if j == -1 else j
        elif src.startswith("/*", i):
            j = src.find("*/", i + 2)
            j = n if j == -1 else j + 2
        if j is not None:
            comments.append((i, j, line, src[i:j], not seen_code))
            blank(i, j)
            line += src.count("\n", i, j)
            code.append(" ")
            i = j
            continue
        prev = src[i - 1] if i else ""
        if c == '"' or (c in "$@" and re.match(r'[$@]+"', src[i:i + 4]) and not (prev.isalnum() or prev == "_")):
            j = skip_string(i)
        elif c == "'":
            m = re.compile(r"'(?:\\u[0-9a-fA-F]{4}|\\x[0-9a-fA-F]{1,4}|\\.|[^\\'\n])'").match(src, i)
            j = m.end() if m else None
        if j is not None:
            q = src.index('"', i) if c != "'" else i
            blank(q + 1, j - 1)
            code.append(src[i:j])
            line += src.count("\n", i, j)
            seen_code = True
            i = j
            continue
        if c == "\n":
            line += 1
        if c.isspace():
            code.append(" ")
        else:
            code.append(c)
            seen_code = True
        i += 1
    return "".join(code).split(), comments, "".join(masked)


def kind_of(text, before_code):
    if DIRECTIVE.match(text):
        return "DIRECTIVE"
    if before_code and re.search(r"copyright|license|licence|SPDX-License-Identifier", text, re.IGNORECASE):
        return "LICENSE"
    if (text.startswith("///") and not text.startswith("////")) or \
            (text.startswith("/**") and not text.startswith(("/**/", "/***"))):
        return "DOC"
    body = text.lstrip("/*! ").upper()
    for tag in ("TODO", "FIXME"):
        if body.startswith(tag):
            return tag
    return "BLOCK" if text.startswith("/*") else "LINE"


# ---------------------------------------------------------------- declarations

def declarations(src, masked):
    """Yield dicts for declarations that carry an access modifier, with enclosing types."""
    decls = {m.start(): m for m in DECL.finditer(masked)}
    stack = [{"vis": "public", "type": True}]
    pending = None
    events = sorted([(p, "decl") for p in decls] + [(m.start(), m.group(0)) for m in re.finditer(r"[{};]", masked)])
    for pos, ev in events:
        if ev == "decl":
            m = decls[pos]
            mods = set(m.group("mods").split())
            if "public" in mods or ("protected" in mods and "private" not in mods):
                vis = "public" if "public" in mods else "protected"
            elif "internal" in mods:
                vis = "internal"
            else:
                vis = "private"
            rest = m.group("rest")
            tm = TYPE_DECL.match(rest)
            pending = vis if tm else None
            parents = [s["vis"] for s in stack]
            if not stack[-1]["type"]:
                continue  # inside a method body or accessor
            yield {"pos": pos + len(m.group(0)) - len(m.group(0).lstrip()), "mods": mods, "vis": vis,
                   "rest": rest, "parents": parents, "type": tm.group(1) if tm else None,
                   "text": " ".join((m.group("mods") + rest).split())}
        elif ev == "{":
            line_start = masked.rfind("\n", 0, pos) + 1
            if pending is not None:
                stack.append({"vis": pending, "type": True})
            elif NAMESPACE.match(masked, line_start) or (
                    masked[line_start:pos].strip() == "" and NAMESPACE.match(masked, masked.rfind("\n", 0, line_start - 1) + 1)):
                stack.append({"vis": "public", "type": True})
            else:
                stack.append({"vis": None, "type": False})
            pending = None
        elif ev == "}":
            if len(stack) > 1:
                stack.pop()
            pending = None
        elif ev == ";" and pending is not None and stack[-1]["type"]:
            pending = None  # record Point(int X, int Y); has no body


def doc_for(decl_line_start, comments, masked):
    """The /// lines (or /** */) directly above a declaration, attributes allowed between."""
    block = []
    for c in reversed([c for c in comments if c[1] <= decl_line_start]):
        gap_end = block[0][0] if block else decl_line_start
        gap = masked[c[1]:gap_end]
        if not re.fullmatch(r"(?:\s|\[[^\]]*\])*", gap) or kind_of(c[3], c[4]) != "DOC":
            break
        if block and not c[3].startswith("///"):
            break
        block.insert(0, c)
        if not c[3].startswith("///"):
            break
    return block


def split_top(text):
    parts, depth, cur = [], 0, ""
    for ch in text:
        if ch in "(<[{":
            depth += 1
        elif ch in ")>]}":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur)
    return parts


def signature(masked, pos):
    """Return (params or None, type_params, returns_void) for the declaration at pos."""
    text = masked[pos:pos + 2000]
    head = re.match(r"(?:(?:" + MODS + r"|delegate|implicit|explicit|operator)\s+)*", text)
    rest = text[head.end():]
    tm = TYPE_DECL.match(rest)
    if tm:
        after = rest[tm.end():]
        tps = re.match(r"\s*<([^>]*)>", after)
        tparams = [t.strip().split()[-1] for t in tps.group(1).split(",")] if tps else []
        pm = re.match(r"\s*(?:<[^>]*>)?\s*\(", after)
        params = None
        if pm:
            close = after.find(")", pm.end())
            params = [p for p in (param_name(x) for x in split_top(after[pm.end():close])) if p]
        return params, tparams, False
    m = re.match(r"([\w.<>\[\]?,\s()]+?)\s+(\w+|this)\s*(<[^()]*>)?\s*[(\[]", rest)
    ctor = re.match(r"(\w+)\s*\(", rest)
    if m:
        ret_type = m.group(1).strip()
        tparams = [t.strip() for t in m.group(3)[1:-1].split(",")] if m.group(3) else []
        open_at = m.end() - 1
    elif ctor:
        ret_type, tparams, open_at = None, [], ctor.end() - 1
    else:
        return None, [], False
    depth, j = 0, open_at
    while j < len(rest):
        if rest[j] in "([":
            depth += 1
        elif rest[j] in ")]":
            depth -= 1
            if depth == 0:
                break
        j += 1
    params = [p for p in (param_name(x) for x in split_top(rest[open_at + 1:j])) if p]
    return params, tparams, ret_type == "void"


def param_name(p):
    p = re.sub(r"\[[^\]]*\]", " ", p).split("=")[0].strip()
    m = re.search(r"(\w+)\s*$", p)
    return m.group(1) if m else None


# ---------------------------------------------------------------- commands

def read(path):
    with open(path, encoding="utf-8-sig") as f:
        return f.read()


def cmd_list(files, internal):
    allowed = ("public", "protected", "internal") if internal else ("public", "protected")
    for path in files:
        src = read(path)
        _, comments, masked = lex(src)
        for _, _, line, text, bc in comments:
            print(f"{path}:{line}: {kind_of(text, bc)}: {' '.join(text.split())[:120]}")
        for d in declarations(src, masked):
            if "override" in d["mods"] or any(v not in allowed for v in d["parents"] + [d["vis"]]):
                continue
            line_start = masked.rfind("\n", 0, d["pos"]) + 1
            if not doc_for(line_start, comments, masked):
                print(f"{path}:{masked.count(chr(10), 0, d['pos']) + 1}: UNDOCUMENTED: {d['text'][:120]}")
    return 0


def cmd_lint(files):
    status = 0
    for path in files:
        src = read(path)
        _, comments, masked = lex(src)
        attached = {}
        for d in declarations(src, masked):
            line_start = masked.rfind("\n", 0, d["pos"]) + 1
            block = doc_for(line_start, comments, masked)
            if block:
                attached[block[0][0]] = (block, d)
        # Enum members and interface members without modifiers have no DECL match; their
        # doc blocks still count as attached if a code line follows directly.
        covered = {c[0] for block, _ in attached.values() for c in block}
        found = []
        for c in comments:
            if kind_of(c[3], c[4]) != "DOC" or c[0] in covered:
                continue
            nxt = masked[c[1]:c[1] + 400]
            if re.match(r"\s*(?:\[[^\]]*\]\s*)*[A-Za-z_]", nxt) and not re.match(r"\s*(?:return|var|if|for|foreach|while)\b", nxt):
                continue
            found.append((c[2], "WARN", "ORPHAN_DOC", "doc comment is not directly above a declaration"))
            covered.add(c[0])
        for start, (block, d) in attached.items():
            line = block[0][2]
            if block[0][3].startswith("///"):
                xml = "\n".join(re.sub(r"^///\s?", "", c[3]) for c in block)
            else:
                xml = re.sub(r"^\s*\*(?!/) ?", "", block[0][3][3:-2], flags=re.M)
            try:
                root = ET.fromstring("<doc>" + xml + "</doc>")
            except ET.ParseError as e:
                found.append((line, "ERROR", "XML_MALFORMED", str(e)))
                continue
            if root.find("inheritdoc") is not None:
                continue
            if root.find("summary") is None and root.find("include") is None:
                found.append((line, "WARN", "SUMMARY_MISSING", "no <summary>"))
            params, tparams, void = signature(masked, d["pos"])
            names = [p.get("name") for p in root.findall("param")]
            if params is not None:
                for nm in names:
                    if nm not in params:
                        found.append((line, "ERROR", "PARAM_UNKNOWN", f'<param name="{nm}">: no such parameter'))
                if names:
                    for p in params:
                        if p not in names:
                            found.append((line, "WARN", "PARAM_MISSING", f"parameter {p} has no <param>"))
            for tp in root.findall("typeparam"):
                if tp.get("name") not in tparams:
                    found.append((line, "ERROR", "TYPEPARAM_UNKNOWN", f'<typeparam name="{tp.get("name")}">: no such type parameter'))
            if void and root.find("returns") is not None:
                found.append((line, "WARN", "RETURNS_ON_VOID", "<returns> on a void method"))
        for line, level, code, msg in sorted(found):
            print(f"{path}:{line}: {level} {code}: {msg}")
            if level == "ERROR":
                status = 1
        if not found:
            print(f"OK {path}")
    return status


def git_show(rev, path):
    r = subprocess.run(["git", "show", f"{rev}:./{path}"], capture_output=True, text=True)
    return r.stdout if r.returncode == 0 else None


def guarded(comments):
    return [(k, " ".join(t.split())) for _, _, _, t, bc in comments
            for k in [kind_of(t, bc)] if k in ("DIRECTIVE", "LICENSE")]


def main(argv):
    if len(argv) < 2 or argv[1] not in ("list", "lint", "snapshot", "check"):
        print(__doc__, file=sys.stderr)
        return 2
    mode, args = argv[1], argv[2:]
    internal = "--internal" in args
    args = [a for a in args if a != "--internal"]
    rev = base = None
    if mode == "check":
        if args[:1] == ["--rev"]:
            rev, args = args[1], args[2:]
        elif args[:1] == ["--base"]:
            base, args = args[1], args[2:]
        else:
            print("check needs --base DIR or --rev REV", file=sys.stderr)
            return 2
    if base is not None and not os.path.isdir(base):
        print(f"snapshot directory not found: {base!r}", file=sys.stderr)
        return 2
    files = [a for a in args if a.endswith(".cs")]
    if not files:
        print("no .cs files given", file=sys.stderr)
        return 2
    if mode == "list":
        return cmd_list(files, internal)
    if mode == "lint":
        return cmd_lint(files)
    if mode == "snapshot":
        out = tempfile.mkdtemp(prefix="csharp-comment-")
        for path in files:
            dest = os.path.join(out, os.path.abspath(path).lstrip(os.sep))
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            shutil.copy2(path, dest)
        print(out)
        return 0
    status = 0
    for path in files:
        tokens, comments, _ = lex(read(path))
        if base is not None:
            copy = os.path.join(base, os.path.abspath(path).lstrip(os.sep))
            old = read(copy) if os.path.exists(copy) else None
        else:
            old = git_show(rev, path)
        if old is None:
            print(f"SKIP {path}: no earlier copy")
            continue
        old_tokens, old_comments, _ = lex(old)
        ok = True
        if old_tokens != tokens:
            ok = False
            k = next((x for x in range(min(len(old_tokens), len(tokens)))
                      if old_tokens[x] != tokens[x]), min(len(old_tokens), len(tokens)))
            print(f"CODE {path}: code changed near\n     was: {' '.join(old_tokens[max(0, k - 5):k + 5])}"
                  f"\n     now: {' '.join(tokens[max(0, k - 5):k + 5])}")
        new_guarded = guarded(comments)
        for kind, text in guarded(old_comments):
            if (kind, text) not in new_guarded:
                ok = False
                print(f"{kind} {path}: changed or removed: {text[:120]}")
        if ok:
            print(f"OK   {path}: only comments/whitespace changed")
        else:
            status = 1
    return status


if __name__ == "__main__":
    sys.exit(main(sys.argv))
